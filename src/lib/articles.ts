/* ── 성냥개비 보드 SVG — MatchstickBoard.svelte와 같은 좌표계 ── */
const SEG_RECT: Record<string, [number, number, number, number]> = {
	a: [10, 0, 34, 8], b: [46, 9, 8, 34], c: [46, 51, 8, 34], d: [10, 87, 34, 8],
	e: [0, 51, 8, 34], f: [0, 9, 8, 34], g: [10, 43.5, 34, 8]
};
const DIGIT_SEGS = ['abcdef', 'bc', 'abdeg', 'abcdg', 'bcfg', 'acdfg', 'acdefg', 'abc', 'abcdefg', 'abcdfg'];
const GW = 54, GAP = 14, OPW = 42, EQW = 36;

/** 등식 하나를 어두운 보드 SVG로. orange에 적힌 자리는 주황(옮겨 온 성냥). */
function boardSvg(eq: string, orange: string[] = []): string {
	const m = eq.match(/^(\d) ([+-]) (\d) = (\d)$/);
	if (!m) throw new Error(`잘못된 등식: ${eq}`);
	const digits = [Number(m[1]), Number(m[3]), Number(m[4])];
	const plus = m[2] === '+';
	const X0 = 0, OPX = X0 + GW + GAP, X1 = OPX + OPW + GAP, EQX = X1 + GW + GAP, X2 = EQX + EQW + GAP;
	const XS = [X0, X1, X2];
	const BW = X2 + GW;
	const L = '#3aff62', O = '#ffb020', G = '#17231a', Y = '#ffd24a';

	const seg = (gi: number, s: string) => {
		const on = DIGIT_SEGS[digits[gi]].includes(s);
		const [rx, ry, rw, rh] = SEG_RECT[s];
		const fill = orange.includes(`g${gi}-${s}`) && on ? O : on ? L : G;
		const stroke = on ? '' : ` stroke="#223528" stroke-width="1"`;
		return `<rect x="${rx}" y="${ry}" width="${rw}" height="${rh}" rx="3" fill="${fill}"${stroke}/>`;
	};
	const glyph = (gi: number) =>
		`<g transform="translate(${XS[gi]} 0)">${Object.keys(SEG_RECT).map((s) => seg(gi, s)).join('')}</g>`;

	return `<svg viewBox="-4 -4 ${BW + 8} 103" role="img" aria-label="${eq}">
		${glyph(0)}
		<g transform="translate(${OPX} 0)">
			<rect x="4" y="43.5" width="34" height="8" rx="3" fill="${Y}"/>
			${plus ? `<rect x="17" y="30" width="8" height="35" rx="3" fill="${orange.includes('op') ? O : L}"/>` : ''}
		</g>
		${glyph(1)}
		<g transform="translate(${EQX} 0)">
			<rect x="1" y="37" width="30" height="7" rx="3" fill="${Y}"/>
			<rect x="1" y="51" width="30" height="7" rx="3" fill="${Y}"/>
		</g>
		${glyph(2)}
	</svg>`;
}

/** 문제→정답 보드 한 쌍 */
const boardPair = (from: string, to: string, orange: string[], cap: string) => `
<figure class="mfig">
	<div class="mrow"><span class="mtag">문제</span><div class="mboard">${boardSvg(from)}</div></div>
	<div class="mrow"><span class="mtag ok">정답</span><div class="mboard">${boardSvg(to, orange)}</div></div>
	<figcaption>${cap}</figcaption>
</figure>`;

