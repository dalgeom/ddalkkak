/**
 * chip이 매핑에 등록돼 있는가. fieldOfChip은 오타 chip을 조용히 '관찰·추리'로
 * 떨어뜨리는데(런타임 안전), 그러면 레인 구성이 소리 없이 바뀐다 —
 * 테스트가 이 함수로 오타를 잡는다.
 */
export function isKnownChip(chip: string): boolean {
	return chip in CHIP_FIELD;
}

/** chip → 상위 분야. 매핑에 없는 chip은 '관찰·추리'로 떨어뜨린다(안전 기본값). */
export function fieldOfChip(chip: string): DiscoverField {
	return CHIP_FIELD[chip] ?? '관찰·추리';
}

/**
 * 푸는 화면에 붙이는 이름(10/22). 발견형 chip은 「삐딱한 선」 · 「끝점」 · 「닫힌 칸」 · 「함정」처럼 규칙을 미리 말해
 * 「아!」를 칩이 먼저 가져갔다(직접 풀어 보고 확인) — 푸는 동안에는 상위 분야만 보이고, chip은 해설 · 분야 쪽에 남긴다.
 * 상식의 chip은 분야(사자성어 · 세계사)라 그대로다.
 */
export function playChip(p: { chip?: string; trivia?: boolean }): string | undefined {
	if (!p.chip) return undefined;
	return p.trivia ? p.chip : fieldOfChip(p.chip);
}

