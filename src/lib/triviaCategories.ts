/**
 * 상식 퀴즈 분야별 페이지(/trivia/<slug>)를 위한 메타데이터.
 *
 * 한글 카테고리명을 URL에 그대로 쓰면 퍼센트 인코딩돼서 공유·사이트맵·canonical이 지저분해진다.
 * 그래서 분야마다 영문 슬러그를 하나씩 고정해 둔다 — 한번 정하면 바꾸지 않는다(색인이 끊긴다).
 *
 * intro는 분야마다 다른 글을 쓴다. 같은 틀에 이름만 바꿔 끼우면 페이지가 서로 복제본으로 보인다.
 */
export type TriviaCategory = {
	/** URL 슬러그 — 변경 금지 */
	slug: string;
	/** trivia.ts의 category 값과 정확히 일치해야 한다 */
	name: string;
	/** 페이지 제목에 쓰는 이름 (검색어에 맞춘 표현) */
	title: string;
	/** 그 분야를 설명하는 두세 문장 (본문에 쓴다) */
	intro: string;
	/**
	 * meta description. 분야마다 다르게 쓴다.
	 *
	 * 원래는 컴포넌트에서 「<분야> 상식 퀴즈 N문제를 정답과 해설까지 한 페이지에
	 * 모았습니다…」 한 문장에 이름과 숫자만 갈아 끼웠다. 18개 페이지의 설명이
	 * 사실상 한 문장이었던 셈이다. 위에 intro를 두고 「같은 틀에 이름만 바꿔
	 * 끼우면 복제본으로 보인다」고 적어 놓고 정작 검색 결과에 나가는 문장에는
	 * 안 지켰다. 2026-09-02에 idiom·geography가 「크롤링됨 - 색인 안 됨」이었다.
	 */
	desc: string;
	/**
	 * 그 분야에서 무엇을 자주 틀리고 어떻게 접근하면 되는지.
	 *
	 * intro가 "이 분야는 무엇인가"라면 이쪽은 "이 분야는 어떻게 푸는가"다. 문제 목록만
	 * 늘어놓으면 어디서나 볼 수 있는 상식 퀴즈와 구분이 안 되므로, 은행을 실제로 훑어보고
	 * 그 분야에 실재하는 함정을 짚는다.
	 */
	deepDive: string;
	/**
	 * 페이지에 싣는 대표 문제.
	 *
	 * 전 문제를 늘어놓던 것을 걷어내고 이것만 남긴다. 그 목록은 어디서나 볼 수 있는
	 * 상식 퀴즈와 구분이 안 되고, 성냥개비 741개를 그렇게 늘어놨다가 애드센스가
	 * 「가치가 별로 없는 콘텐츠」로 두 번 반려한 근거가 됐다(matchstickKinds.ts 참조).
	 * 나머지 문제는 무한 연습에서 만난다 — 페이지가 이미 그리로 링크하고 있다.
	 *
	 * why는 「사람들이 여기서 무엇을 어떻게 틀리나」다. 해설을 줄여 쓰는 자리가 아니다 —
	 * 해설은 그 문제의 답을 설명하고, why는 그 문제를 대표로 고른 이유를 설명한다.
	 */
	featured: {
		/** trivia.ts의 id */
		id: string;
		/** 왜 이 문제를 골랐나 · 사람들이 어디서 헛짚나 (60~100자) */
		why: string;
	}[];
};

