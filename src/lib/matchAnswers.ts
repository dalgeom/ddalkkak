/** 주소 이름 — 12-7=6 → 12-minus-7-6 (경로에 + 와 = 를 넣지 않는다) */
export function answerSlug(q: string): string {
	return q.replace(/[+\-=]/g, (c) => (c === '+' ? '-plus-' : c === '-' ? '-minus-' : '-'));
}

export function answerBySlug(slug: string): MatchAnswer | undefined {
	return MATCH_ANSWERS.find((a) => answerSlug(a.q) === slug);
}

export function cellsOf(q: string): Cell[] {
	return (parseCells(q) as { cells: Cell[] }).cells;
}

/** 답이 있는 첫 규칙 — 쪽 제목의 규칙(정답 찾기 「많이 찾는 문제」와 같은 기준) */
export function mainRule(q: string): MatchRule {
	const cells = cellsOf(q);
	return RULES.find((r) => solve(cells, r).length)!;
}
